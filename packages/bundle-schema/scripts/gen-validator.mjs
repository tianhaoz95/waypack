// Compiles manifest.v1.schema.json into a standalone validator module.
// Workers forbid `new Function`, so Ajv must run at build time, not runtime.
import Ajv from "ajv";
import addFormats from "ajv-formats";
import standaloneCode from "ajv/dist/standalone/index.js";
import { readFileSync, writeFileSync, mkdirSync, rmSync } from "node:fs";
import { buildSync } from "esbuild";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const schema = JSON.parse(readFileSync(join(root, "manifest.v1.schema.json"), "utf8"));
const ajv = new Ajv({ allErrors: true, strict: false, code: { source: true, esm: true } });
addFormats(ajv, ["date", "uuid"]);
const validate = ajv.compile(schema);
const out = join(root, "src/generated");
mkdirSync(out, { recursive: true });
// Ajv's standalone output still require()s a few runtime helpers; bundle them in so the
// result is dependency-free ESM that runs in Workers, browsers and Node alike.
const raw = join(out, "validate-manifest.raw.mjs");
writeFileSync(raw, standaloneCode(ajv, validate));
const bundled = buildSync({ entryPoints: [raw], bundle: true, format: "esm", platform: "neutral", write: false, minify: false, mainFields: ["main", "module"] });
rmSync(raw);
writeFileSync(join(out, "validate-manifest.js"), "// @ts-nocheck\n// GENERATED by scripts/gen-validator.mjs — do not edit.\n" + bundled.outputFiles[0].text);
writeFileSync(
  join(out, "validate-manifest.d.ts"),
  "declare const validate: ((data: unknown) => boolean) & { errors?: Array<{ instancePath: string; message?: string; keyword: string; params: Record<string, unknown> }> | null };\nexport default validate;\n",
);
writeFileSync(join(out, "schema.js"), "// GENERATED\nexport default " + JSON.stringify(schema) + ";\n");
writeFileSync(join(out, "schema.d.ts"), "declare const schema: Record<string, unknown>;\nexport default schema;\n");
console.log("generated validator");
